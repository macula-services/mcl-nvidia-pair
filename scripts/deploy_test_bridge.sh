#!/usr/bin/env bash
# Build and run the bridge ON THE BOX beside PAIR, as a throwaway named
# vesta-pair8-*, for the live test in mcl-nvidia-pair#8.
#
# WHAT THIS IS FOR: the live test has to call a DEPLOYED bridge from another
# machine. Until the first signed release exists there is no image for this
# code, so the box builds one from a named git ref and runs it OUTSIDE the
# fleet's own units — a `podman run' with a name this script owns, never a
# Quadlet, never a file under ~/.config/containers/systemd. Removal is one
# command (`stop'), and nothing survives it but the identity volume.
#
#   ./scripts/deploy_test_bridge.sh start      # build (if needed) and run
#   ./scripts/deploy_test_bridge.sh status     # is it up, and how does it look
#   ./scripts/deploy_test_bridge.sh logs [n]   # the last n log lines
#   ./scripts/deploy_test_bridge.sh stop       # remove the container
#
# ⛔ WHAT IT DOES NOT DO: admit anything on the realm. A service claims, the
# realm's operator admits the claim on the Providers desk, and only then is a
# delegation issued (mcl_om's boot-claim flow). This script reports the node id
# the operator has to admit and nothing else.
#
# ⚠ THE REALM, ITS KEY AND THE STATIONS COME FROM THE ENVIRONMENT FILE, never
# from this script: this repository is public, and a lab's hostnames, station
# node ids and realm belong to the deployment. Point PAIR8_ENV_FILE at a file
# outside git that sets them (the fleet's own pattern, ~/.macula/secrets/*.env).
set -euo pipefail

REF=${PAIR8_REF:?set PAIR8_REF to the git ref to build (a branch, tag or commit)}
REPO=${PAIR8_REPO:-https://github.com/macula-services/mcl-nvidia-pair.git}
WORK=${PAIR8_WORK:-$HOME/vesta-pair8}
ENV_FILE=${PAIR8_ENV_FILE:-$HOME/.macula/secrets/mcl-nvidia-pair.env}
NAME=${PAIR8_CONTAINER:-vesta-pair8-bridge}
# A branch name is not an image tag: `vesta/pair-8-wire' is an invalid
# reference, so the tag is the ref with its separators flattened.
TAG=$(printf '%s' "$REF" | tr '/:' '--')
IMAGE=${PAIR8_IMAGE:-localhost/vesta-pair8-bridge:${TAG}}
VOLUME=${PAIR8_VOLUME:-vesta-pair8-secrets}
HEALTH_PORT=${PAIR8_HEALTH_PORT:-8499}

say() { printf '\n== %s\n' "$*"; }
die() { printf '%s\n' "$*" >&2; exit 1; }

# Every variable the container needs from the file. Checked by NAME only: a
# value is never printed, and the identity key is not in this file at all (it
# lives on the volume, generated by mcl_om on first boot).
REQUIRED=(MCL_REALM MCL_REALM_KEY MACULA_STATION_SEEDS MACULA_STATION_NODE_IDS)

# The box already carries the realm and the stations, in the fleet's own unit
# for a service that lives there. Deriving the file from it is not laziness: it
# keeps one source of truth for values this PUBLIC repository must not hold
# (a lab's stations are not ours to publish), and it means nobody retypes a
# 2500-character key. PAIR8_FLEET_UNIT names the unit; with none given, the
# first unit under the fleet's edge directory that carries MCL_REALM is used.
FLEET_DIR=${PAIR8_FLEET_DIR:-$HOME/gitops/macula-fleet/edge}
FLEET_UNIT=${PAIR8_FLEET_UNIT:-}
[ -n "$FLEET_UNIT" ] || [ ! -d "$FLEET_DIR" ] ||
    FLEET_UNIT=$(grep -rlE '^Environment=MCL_REALM=' --include='*.container' "$FLEET_DIR" 2>/dev/null | head -1)

ensure_env_file() {
    if [ -f "$ENV_FILE" ]; then
        checked_env_file
        return
    fi
    [ -n "$FLEET_UNIT" ] && [ -f "$FLEET_UNIT" ] ||
        die "no environment file at $ENV_FILE and no fleet unit under $FLEET_DIR to derive one from (set PAIR8_ENV_FILE or PAIR8_FLEET_UNIT)"
    say "derive $ENV_FILE from $(basename "$FLEET_UNIT") (values are not printed)"
    umask 077
    mkdir -p "$(dirname "$ENV_FILE")"
    : > "$ENV_FILE"
    local name value
    for name in "${REQUIRED[@]}"; do
        value=$(sed -n "s/^Environment=${name}=//p" "$FLEET_UNIT" | tail -1)
        [ -n "$value" ] || die "$FLEET_UNIT does not set $name"
        printf '%s=%s\n' "$name" "$value" >> "$ENV_FILE"
    done
    checked_env_file
}

checked_env_file() {
    [ -f "$ENV_FILE" ] || die "no environment file at $ENV_FILE (set PAIR8_ENV_FILE)"
    local name
    for name in "${REQUIRED[@]}"; do
        grep -qE "^${name}=.+" "$ENV_FILE" || die "$ENV_FILE does not set $name"
    done
}

checkout() {
    if [ -d "$WORK/.git" ]; then
        git -C "$WORK" fetch --quiet origin
    else
        mkdir -p "$(dirname "$WORK")"
        git clone --quiet "$REPO" "$WORK"
    fi
    git -C "$WORK" checkout --quiet "$REF"
    git -C "$WORK" log -1 --format='%H %s'
}

# `podman build' from the checked-out tree. No --network host on a fleet box:
# the default bridge network has what this build needs (hex, github, rustup).
build() {
    local have
    have=$(podman image exists "$IMAGE" && echo yes || echo no)
    if [ "$have" = yes ] && [ "${PAIR8_REBUILD:-0}" != 1 ]; then
        say "image $IMAGE already here (PAIR8_REBUILD=1 rebuilds)"
        return
    fi
    say "build $IMAGE"
    podman build --tag "$IMAGE" \
                 --build-arg REVISION="$(git -C "$WORK" rev-parse HEAD)" \
                 --file "$WORK/Containerfile" "$WORK"
}

run() {
    say "run $NAME"
    podman rm --force "$NAME" >/dev/null 2>&1 || true
    podman run --detach \
        --name "$NAME" \
        --network host \
        --env-file "$ENV_FILE" \
        --env PAIR_BASE_URL="${PAIR_BASE_URL:-http://127.0.0.1:11435}" \
        --env PAIR_MAX_PER_WINDOW="${PAIR_MAX_PER_WINDOW:-20}" \
        --env PAIR_WINDOW_SECONDS="${PAIR_WINDOW_SECONDS:-60}" \
        --env MCL_SERVICE_NAME="${MCL_SERVICE_NAME:-mcl-nvidia-pair}" \
        --env "MCL_BOX=$(hostname)" \
        --env "MCL_HEALTH_PORT=$HEALTH_PORT" \
        --volume "$VOLUME:/etc/mcl/secrets" \
        "$IMAGE"
}

# /health answers 503 until the realm grants this node its procedure, and that
# is the expected state until an operator admits the claim. So a 503 here is
# reported, not treated as a failure: the third state a reader needs.
report() {
    local body code
    body=$(curl -sS --max-time 5 -w '\n%{http_code}' "http://127.0.0.1:${HEALTH_PORT}/health" || true)
    code=${body##*$'\n'}
    printf 'health: HTTP %s\n%s\n' "${code:-none}" "${body%$'\n'*}"
}

identity() {
    podman exec "$NAME" /app/bin/mcl_nvidia_pair eval \
        'ok = io:format("~s~n", [binary:encode_hex(element(2, macula_node_keys:node_id(mcl_om_identity:node_key())), lowercase)]).' 2>/dev/null ||
    podman exec "$NAME" cat /etc/mcl/secrets/identity.key >/dev/null 2>&1 ||
    die "could not read the node identity from the container"
}

case ${1:-start} in
    start)
        ensure_env_file
        say "check out $REF"
        checkout
        build
        run
        say "wait for /health"
        for _ in $(seq 1 60); do
            curl -sS --max-time 2 -o /dev/null "http://127.0.0.1:${HEALTH_PORT}/health" 2>/dev/null && break
            sleep 2
        done
        report
        say "next: admit this service on the realm's Providers desk, then run the live test from the other machine"
        ;;
    status)
        podman ps --filter "name=^${NAME}$" --format '{{.Names}} {{.Status}} {{.Image}}' || true
        report
        ;;
    stop)
        podman rm --force "$NAME" >/dev/null 2>&1 && echo "removed $NAME" || echo "$NAME was not running"
        echo "the identity volume $VOLUME stays, so a redeploy keeps the same node id; 'podman volume rm $VOLUME' retires it"
        ;;
    identity)
        die "the node id is not read out of the container: the realm's Providers desk shows it on the pending claim, next to MCL_SERVICE_NAME and MCL_BOX"
        ;;
    logs)
        podman logs --tail "${2:-40}" "$NAME"
        ;;
    *)
        die "usage: $0 [start|status|logs|stop]"
        ;;
esac
